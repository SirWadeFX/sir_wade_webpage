/* ==========================================================================
   BUILD
   Builds every page under pages/. For each page:

     shared/css/*.css + pages/<page>/src/css/*.css → pages/<page>/dist/sirwade.css
     shared/js/*.js   + pages/<page>/src/js/*.js   → pages/<page>/dist/sirwade.js
     pages/<page>/blocks/*.html                    → pages/<page>/preview.html
     pages/<page>/preview-variants.json (optional) → pages/<page>/preview-<name>.html

   A variant is the same page with extra CSS injected after the head
   snippet, e.g. {"compact": ":root { --sw-page-max: 1440px; }"} — the
   same line you'd add to that page's head snippet in Kajabi.

   Shared and page files are merged and sorted by filename, so the numeric
   prefixes control cascade order across both: shared 10-nav lands before a
   page's 20-hero, shared 90-footer after a page's 30-catalog. Two files
   with the same name would make that order ambiguous, so it's an error.

   No bundler, no dependencies, no node_modules — jsDelivr serves the dist
   files straight from the repo, so the build has to stay trivially
   inspectable.

     node build.mjs              # every page
     node build.mjs home         # just one
   ========================================================================== */

import { readdir, readFile, writeFile, mkdir, access } from "node:fs/promises";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const pagesDir = join(root, "pages");

/* Deliberately no build timestamp: the output has to be deterministic, or
   every rebuild dirties dist/ with a one-line diff and real changes get lost
   in the noise. Use `git log pages/<page>/dist/` to see when a bundle last
   changed. */
const banner = (kind, page) =>
  `/*! Sir Wade — ${page} ${kind} bundle
 *  Generated by build.mjs. DO NOT EDIT THIS FILE.
 *  Edit shared/${kind.toLowerCase()}/ or pages/${page}/src/${kind.toLowerCase()}/ and re-run: node build.mjs
 */\n\n`;

async function list(dir, ext) {
  try {
    return (await readdir(dir))
      .filter((f) => f.endsWith(ext))
      .map((f) => join(dir, f));
  } catch (err) {
    if (err.code === "ENOENT") return [];
    throw err;
  }
}

async function concat(dirs, ext) {
  const files = (await Promise.all(dirs.map((d) => list(d, ext)))).flat();
  files.sort((a, b) => basename(a).localeCompare(basename(b)));

  for (let i = 1; i < files.length; i++) {
    if (basename(files[i]) === basename(files[i - 1])) {
      throw new Error(
        `Two files named ${basename(files[i])}:\n  ${files[i - 1]}\n  ${files[i]}\n` +
          "Rename one — shared and page files share a single ordering.",
      );
    }
  }

  const parts = [];
  for (const file of files) {
    const text = await readFile(file, "utf8");
    // A "*/" inside a comment (e.g. a path like pages/*/blocks) closes it
    // early, and the browser then silently drops the next rule. Once every
    // comment is stripped, any leftover "*/" means exactly that happened.
    if (ext === ".css") {
      const stray = text.replace(/\/\*[\s\S]*?\*\//g, "").indexOf("*/");
      if (stray !== -1) {
        const line = text.slice(0, text.indexOf("*/", 0) + 1).split("\n").length;
        throw new Error(
          `${file}: a comment closes early (stray "*/"), near line ${line}. ` +
            'Don\'t write "*/" inside a comment.',
        );
      }
    }
    parts.push(text);
  }
  return { files, body: parts.join("\n") };
}

/* Brand fonts the live site loads from Kajabi, which a local preview can't
   (Kajabi sends no CORS header). If a copy sits in the git-ignored
   .local-fonts/, previews load it, so they match Kajabi instead of showing
   the Google fallback. Never commit these: the repo is public. */
const LOCAL_FONTS = [
  { family: "PalmerLakePrint", file: "PalmerLakePrint-Regular.ttf" },
];

async function localFontFaces() {
  const rules = [];
  for (const { family, file } of LOCAL_FONTS) {
    try {
      await access(join(root, ".local-fonts", file));
      rules.push(
        `@font-face{font-family:"${family}";src:url("../../.local-fonts/${file}") format("truetype");font-display:swap}`,
      );
    } catch {}
  }
  return rules.length
    ? `\n<!-- Local copies from .local-fonts/ (git-ignored) -->\n<style>${rules.join("")}</style>`
    : "";
}

async function buildPreview(page, variant = null) {
  const dir = join(pagesDir, page, "blocks");
  const files = (await list(dir, ".html"))
    .map((f) => basename(f))
    .filter((f) => f !== "00-head.html")
    .sort();

  const sections = [];
  for (const file of files) {
    sections.push(await readFile(join(dir, file), "utf8"));
  }

  // The head block's CDN <link>/<script> are replaced with local paths so the
  // preview reflects uncommitted work instead of whatever is live on jsDelivr.
  const head = (await readFile(join(dir, "00-head.html"), "utf8"))
    .replace(
      /<link\s+rel="stylesheet"\s+href="https:\/\/cdn\.jsdelivr[\s\S]*?\/>/,
      '<link rel="stylesheet" href="dist/sirwade.css" />',
    )
    .replace(
      /<script\s+defer[\s\S]*?><\/script>/,
      '<script defer src="dist/sirwade.js"></script>',
    );

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Sir Wade — ${page}${variant ? ` (${variant.name})` : ""} preview</title>
<!-- GENERATED by build.mjs from pages/${page}/blocks/*.html — do not edit directly. -->
<style>body{margin:0;background:#fff}</style>
${head}${await localFontFaces()}
<!-- Repo-hosted assets load from the working tree in previews -->
<script>window.SW_LOCAL_ASSETS = "../../assets/";</script>${variant ? `\n<!-- Variant "${variant.name}" from preview-variants.json -->\n<style>\n${variant.css}\n</style>` : ""}
</head>
<body>
${sections.join("\n")}
</body>
</html>
`;
}

async function buildPage(page) {
  const base = join(pagesDir, page);
  const css = await concat(
    [join(root, "shared/css"), join(base, "src/css")],
    ".css",
  );
  const js = await concat([join(root, "shared/js"), join(base, "src/js")], ".js");

  await mkdir(join(base, "dist"), { recursive: true });
  await writeFile(
    join(base, "dist/sirwade.css"),
    banner("CSS", page) + css.body,
    "utf8",
  );
  await writeFile(
    join(base, "dist/sirwade.js"),
    banner("JS", page) + js.body,
    "utf8",
  );
  await writeFile(join(base, "preview.html"), await buildPreview(page), "utf8");

  let variants = {};
  try {
    variants = JSON.parse(
      await readFile(join(base, "preview-variants.json"), "utf8"),
    );
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }
  for (const [name, css] of Object.entries(variants)) {
    await writeFile(
      join(base, `preview-${name}.html`),
      await buildPreview(page, { name, css }),
      "utf8",
    );
  }
  const extra = Object.keys(variants).map((n) => ` · preview-${n}.html`).join("");

  console.log(
    `${page.padEnd(14)} css ← ${css.files.length} files · js ← ${js.files.length} files · preview.html${extra}`,
  );
}

const all = (await readdir(pagesDir, { withFileTypes: true }))
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const wanted = process.argv.slice(2);
for (const page of wanted) {
  if (!all.includes(page)) {
    console.error(`No such page: ${page}. Pages: ${all.join(", ")}`);
    process.exit(1);
  }
}

for (const page of wanted.length ? wanted : all) await buildPage(page);
